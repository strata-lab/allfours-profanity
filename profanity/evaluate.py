"""Evaluate the released model (profanity/models/current) and write profanity/reports/eval.md.

    python profanity/evaluate.py

Held-out data: the test split (profanity/dataset/test.tsv) and the hand-written sets (profanity/eval); plus
words/must_allow.txt (training negatives on purpose: checked as a guarantee). Reports precision and recall for:
  * the BASE model (unitary/toxic-bert, no fine-tuning) on raw handles and on normalised ones;
  * the fine-tuned model alone, the term match alone, and both together (the verdict).
Exits non-zero if any must-allow text or any hand-written innocent text is flagged.
"""
from __future__ import annotations

import json
import statistics
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from detoxify import profanity as U  # noqa: E402

HERE = ROOT / "profanity"
REQUIRED_INNOCENT = ["Cocktail", "Scunthorpe", "Grasshopper", "Dickens"]


def prf(pred: list[bool], labels: list[int]) -> dict:
    tp = sum(1 for p, y in zip(pred, labels) if p and y)
    fp = sum(1 for p, y in zip(pred, labels) if p and not y)
    fn = sum(1 for p, y in zip(pred, labels) if not p and y)
    tn = len(pred) - tp - fp - fn
    return {"precision": tp / (tp + fp) if tp + fp else 1.0, "recall": tp / (tp + fn) if tp + fn else 1.0,
            "fpr": fp / (fp + tn) if fp + tn else 0.0, "tp": tp, "fp": fp, "fn": fn, "tn": tn}


def row(name: str, m: dict) -> str:
    return (f"| {name} | {m['precision']:.3f} | {m['recall']:.3f} | {m['fpr']:.3%} | {m['tp']} | {m['fp']} | "
            f"{m['fn']} | {m['tn']} |")


HEADER = "| | Precision | Recall | False-positive rate | TP | FP | FN | TN |\n| --- | --- | --- | --- | --- | --- | --- | --- |"


def hand_set(name: str) -> list[str]:
    return [ln.strip() for ln in (HERE / "eval" / name).read_text().splitlines() if ln.strip() and not ln.startswith("#")]


def read(split: str) -> list[tuple[str, int, str]]:
    rows = []
    for ln in (HERE / "dataset" / f"{split}.tsv").read_text().splitlines()[1:]:
        h, label, group, _ = ln.split("\t")
        rows.append((h, int(label), group))
    return rows


class Base:
    """The base model as released (unitary/toxic-bert, no fine-tuning): its toxicity score for a text."""

    def __init__(self, path: Path):
        import torch
        from transformers import AutoModelForSequenceClassification, AutoTokenizer

        self.torch, self.tok = torch, AutoTokenizer.from_pretrained(path)
        self.model = AutoModelForSequenceClassification.from_pretrained(path).eval()

    def scores(self, texts: list[str]) -> list[float]:
        out = []
        with self.torch.no_grad():
            for i in range(0, len(texts), 256):
                enc = self.tok(texts[i:i + 256], return_tensors="pt", truncation=True, padding=True)
                out.extend(self.torch.sigmoid(self.model(**enc).logits[:, 0]).tolist())
        return out


def batched(fn, items: list[str], n: int = 256) -> list[float]:
    out: list[float] = []
    for i in range(0, len(items), n):
        out.extend(fn(items[i:i + n]))
    return out


def main() -> None:
    model_dir = HERE / "models" / "current"
    out_path = HERE / "reports" / "eval.md"
    tuned = U.Profanity(model_dir)
    meta, threshold, matcher = tuned.meta, tuned.threshold, tuned.matcher
    base = Base(HERE / "base" / "toxic-bert")

    test = read("test")
    good, bad = hand_set("innocent.txt"), hand_set("offensive.txt")
    hand = [(h, 0) for h in good] + [(h, 1) for h in bad]
    allow = U.must_allow()

    out: list[str] = ["# Profanity in compact text: evaluation report", "",
                      f"Generated by `profanity/evaluate.py`. Base `{meta['base']}`, fine-tuned with upstream's "
                      f"`train.py` on `{meta['config']}`; dataset sha256 `{meta['dataset_sha256'][:16]}`. Threshold "
                      f"**{threshold:.2f}**: the best dev F1 ({meta['dev_f1']:.4f}) flagging at most "
                      f"{meta['dev_fpr_cap']:.0%} of innocent dev texts ({meta['dev_fpr']:.2%}) and no must-allow text. "
                      "Every number below is on data the model never trained on, except the must-allow texts.", ""]

    def section(title: str, rows: list[tuple[str, int]], note: str = "") -> dict:
        hs, ys = [r[0] for r in rows], [r[1] for r in rows]
        b_raw = base.scores(hs)
        b_norm = base.scores([U.text(h) for h in hs])
        t = batched(tuned.scores, hs)
        hits = [matcher.match(h) is not None for h in hs]
        results = {
            "Base model, raw handle (threshold 0.50)": prf([s >= 0.5 for s in b_raw], ys),
            "Base model, normalised (threshold 0.50)": prf([s >= 0.5 for s in b_norm], ys),
            f"Fine-tuned model alone (threshold {threshold:.2f})": prf([s >= threshold for s in t], ys),
            "Term match alone (whole words)": prf(hits, ys),
            "**Verdict: fine-tuned model + term match**": prf([s >= threshold or h for s, h in zip(t, hits)], ys),
        }
        out.extend([f"## {title}", ""] + ([note, ""] if note else []) + [HEADER]
                   + [row(k, v) for k, v in results.items()] + [""])
        return {"hs": hs, "ys": ys, "t": t, "hits": hits}

    n_pos = sum(r[1] for r in test)
    section("Test split", [(r[0], r[1]) for r in test],
            f"{len(test)} synthetic handles ({n_pos} offensive, {len(test) - n_pos} innocent, of which "
            f"{sum(1 for r in test if r[2] == 'hard_negative')} hard negatives that contain a short term).")
    for group, note in (("unseen_term", "Offensive handles built from terms held out of training, plus all innocent rows."),
                        ("seen_term", "Fresh spellings of terms the model trained on, plus all innocent rows.")):
        section(f"Test split: {group.replace('_', ' ')}s",
                [(r[0], r[1]) for r in test if r[2] in (group, "negative", "hard_negative")], note)
    # Nakama-style random default names (10 mixed-case letters), from a seed the dataset never used
    import random as _random

    keys = {t.key for t in U.load_terms()}
    rnd = _random.Random(20261028)
    salad = []
    while len(salad) < 1000:
        h = "".join(rnd.choice("abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ") for _ in range(10))
        if not any(k in f.replace(" ", "") for f in U.forms(h) for k in keys if len(k) >= 3):
            salad.append(h)
    section("Random default names", [(h, 0) for h in salad],
            "1000 random 10-letter mixed-case names like Nakama's defaults (`WqfyfQvdEi`), none containing a term, from "
            "a seed the dataset never used. All innocent, so only the false-positive rate means anything here.")
    hr = section("Hand-written handles", hand,
                 f"{len(good)} innocent (many contain an offensive substring: {', '.join(REQUIRED_INNOCENT)}, ...) and "
                 f"{len(bad)} offensive, written by hand in `profanity/eval/` and never trained on.")

    a_scores = batched(tuned.scores, allow)
    a_flagged = [(h, sc) for h, sc in zip(allow, a_scores) if sc >= threshold or matcher.match(h) is not None]
    top = max(range(len(a_scores)), key=a_scores.__getitem__)
    out.extend(["## Must-allow texts", "",
                f"`profanity/words/must_allow.txt` ({len(allow)} texts; today, every name All Fours' first-launch "
                "generator makes). These are TRAINING negatives on purpose and the threshold is picked above them, so "
                "this checks a guarantee rather than measuring on held-out data.", "",
                f"* Flagged: **{len(a_flagged)} of {len(allow)}**",
                f"* Highest score: {a_scores[top]:.4f} (`{allow[top]}`), threshold {threshold:.2f}", ""])

    wrong = [(h, y, s, m) for h, y, s, m in zip(hr["hs"], hr["ys"], hr["t"], hr["hits"]) if (s >= threshold or m) != bool(y)]
    out.extend(["## Hand-written handles the verdict gets wrong", ""])
    if wrong:
        out.extend(["| Handle | Should be | Score | Term match |", "| --- | --- | --- | --- |"])
        out.extend(f"| `{h}` | {'profane' if y else 'innocent'} | {s:.3f} | {'yes' if m else 'no'} |" for h, y, s, m in wrong)
    else:
        out.append("None.")
    out.append("")

    req = {h: (s, m) for h, s, m in zip(hr["hs"], hr["t"], hr["hits"]) if h in REQUIRED_INNOCENT}
    out.extend(["## Required innocent names", "", "| Handle | Score | Not flagged |", "| --- | --- | --- |"]
               + [f"| `{h}` | {req[h][0]:.4f} | {'yes' if req[h][0] < threshold and not req[h][1] else '**NO**'} |"
                  for h in REQUIRED_INNOCENT] + [""])

    lat = []
    for h in allow[:40] + bad[:40]:
        t0 = time.perf_counter()
        tuned.scores([h])
        lat.append((time.perf_counter() - t0) * 1000)
    out.extend(["## Latency", "", f"One handle per call on this machine's CPU, after warm-up: median "
                f"{statistics.median(lat):.1f} ms, worst {max(lat):.1f} ms ({len(lat)} calls).", ""])

    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text("\n".join(out))
    print(f"wrote {out_path}", file=sys.stderr)
    bad_innocent = [h for h, y, s, m in wrong if not y]
    if a_flagged or bad_innocent:
        print(f"FAIL: {len(a_flagged)} must-allow texts and {len(bad_innocent)} hand-written innocent texts flagged: "
              f"{[h for h, _ in a_flagged][:10]} {bad_innocent[:10]}", file=sys.stderr)
        sys.exit(1)


if __name__ == "__main__":
    main()
